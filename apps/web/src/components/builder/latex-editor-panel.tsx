/**
 * Real-time LaTeX Live Compiler and Source Editor Panel.
 * Generates compilable LaTeX source code from the resume model in real-time,
 * provides live compilation status, and enables instant PDF compilation & download.
 */

'use client';

import { useState, useEffect, useMemo, useRef } from 'react';
import {
  Card,
  CardContent,
  CardHeader,
  CardTitle,
  CardDescription,
  Button,
} from '@resume-builder/ui';
import {
  Code2,
  Play,
  Copy,
  Check,
  FileCode,
  FileDown,
  Terminal,
  Zap,
  Sparkles,
  RotateCcw,
} from 'lucide-react';
import { createEmptyContent, type ResumeDraft, type Theme } from '@resume-builder/types';
import {
  resumeToLatexFromMetadata,
  compileLatexDocument,
  buildExportFilename,
  type CompilerDiagnostic,
} from '@resume-builder/pdf';
import { triggerFileSave } from '@resume-builder/pdf/browser';
import { API_URL } from '@/lib/env';
import { aiEnhanceResume, aiParseLatex } from '@/lib/api';
import { toast } from 'sonner';

interface LatexEditorPanelProps {
  draft: ResumeDraft;
  theme: Theme;
  template?: string;
  updateDraft?: (patch: Partial<ResumeDraft>) => void;
}

export function LatexEditorPanel({ draft, theme: _theme, template: _template, updateDraft }: LatexEditorPanelProps) {
  // Generate real-time LaTeX source from the current resume draft
  const autoGeneratedLatex = useMemo(() => {
    if (!draft.content) return '';
    return resumeToLatexFromMetadata(draft.content, draft.metadata);
  }, [draft.content, draft.metadata]);

  const [latexSource, setLatexSource] = useState(autoGeneratedLatex);
  const [isCustomEdited, setIsCustomEdited] = useState(false);
  const [copied, setCopied] = useState(false);
  const [compiling, setCompiling] = useState(false);
  const [aiEnhancing, setAiEnhancing] = useState(false);
  const [realtimeSync, setRealtimeSync] = useState(true);
  const [lastCompiledAt, setLastCompiledAt] = useState<string | null>(null);
  const [diagnostics, setDiagnostics] = useState<CompilerDiagnostic[]>([]);
  const [compileLogs, setCompileLogs] = useState<string[]>([
    'Compiler engine initialized: Real-Time LaTeX Engine (pdflatex AST compatible)',
    'Ready for real-time document compilation & bidirectional sync.',
  ]);
  const [pdfBlobUrl, setPdfBlobUrl] = useState<string | null>(null);
  const [compiledBlob, setCompiledBlob] = useState<Blob | null>(null);

  // Track the JSON representation of content compiled from LaTeX to distinguish self-mutations from external mutations
  const lastSelfCompiledContentJsonRef = useRef<string>('');

  // 1. Sync auto-generated LaTeX when draft.content changes from outside (Content Editor, AI Studio, Template switcher)
  const currentDraftJson = useMemo(() => JSON.stringify(draft.content || {}), [draft.content]);

  useEffect(() => {
    // If the change did not originate from this LaTeX editor, refresh the LaTeX source
    if (currentDraftJson !== lastSelfCompiledContentJsonRef.current) {
      lastSelfCompiledContentJsonRef.current = currentDraftJson;
      setLatexSource(autoGeneratedLatex);
      setIsCustomEdited(false);
    }
  }, [currentDraftJson, autoGeneratedLatex]);

  // 2. Real-time LaTeX compilation & live sync into resume draft (even if user deletes everything!)
  useEffect(() => {
    if (!isCustomEdited || !realtimeSync) return;

    const timer = setTimeout(() => {
      try {
        if (!latexSource.trim()) {
          const empty = createEmptyContent();
          lastSelfCompiledContentJsonRef.current = JSON.stringify(empty);
          if (updateDraft) {
            updateDraft({ content: empty });
          }
          const timestamp = new Date().toLocaleTimeString();
          setLastCompiledAt(timestamp);
          setDiagnostics([]);
          setCompileLogs([
            `[${timestamp}] Real-time sync: LaTeX source is empty.`,
            `[${timestamp}] Live preview and Content Editor sections cleared to empty.`,
          ]);
          return;
        }

        const result = compileLatexDocument(latexSource);
        const compiledJson = JSON.stringify(result.content);
        lastSelfCompiledContentJsonRef.current = compiledJson;

        if (updateDraft) {
          updateDraft({
            content: result.content,
            metadata: {
              ...draft.metadata,
              ...(result.metadata?.pageSize ? { pageSize: result.metadata.pageSize } : {}),
              ...(result.metadata?.pageMargin ? { pageMargin: result.metadata.pageMargin } : {}),
              ...(result.metadata?.theme ? { theme: { ...draft.metadata?.theme, ...result.metadata.theme } } : {}),
            },
          });
        }
        const timestamp = new Date().toLocaleTimeString();
        setLastCompiledAt(timestamp);
        setDiagnostics(result.diagnostics);
        setCompileLogs([
          `[${timestamp}] Real-time sync: ${result.stats.lineCount} lines, ${result.stats.sectionCount} sections compiled in ${result.stats.parseTimeMs}ms.`,
          `[${timestamp}] Live preview and Content Editor sections synchronized.`,
          ...result.diagnostics
            .filter((d) => d.type !== 'info')
            .map((d) => `[${timestamp}] ${d.type.toUpperCase()} (L${d.line}): ${d.message}`),
        ]);
      } catch (err: unknown) {
        const msg = err instanceof Error ? err.message : 'Syntax error';
        setDiagnostics([{ line: 1, type: 'error', message: msg }]);
      }
    }, 200);

    return () => clearTimeout(timer);
  }, [latexSource, isCustomEdited, realtimeSync, draft.metadata, updateDraft]);

  const handleCopy = () => {
    navigator.clipboard.writeText(latexSource);
    setCopied(true);
    toast.success('LaTeX source copied to clipboard!');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadTex = async () => {
    const filename = buildExportFilename(draft.content, draft.title, 'tex');
    const blob = new Blob([latexSource], { type: 'text/plain;charset=utf-8' });
    const saved = await triggerFileSave(blob, filename);
    if (saved) toast.success(`Saved ${filename}`);
  };

  const handleSyncToForm = () => {
    if (!updateDraft) return;
    try {
      if (!latexSource.trim()) {
        const empty = createEmptyContent();
        lastSelfCompiledContentJsonRef.current = JSON.stringify(empty);
        updateDraft({ content: empty });
        toast.success('Document cleared in visual Content Editor and Live Preview!');
        return;
      }
      const result = compileLatexDocument(latexSource);
      lastSelfCompiledContentJsonRef.current = JSON.stringify(result.content);
      updateDraft({
        content: result.content,
      });
      toast.success('LaTeX changes synced into visual Content Editor!');
    } catch {
      toast.error('Could not sync LaTeX back to form.');
    }
  };

  const handleResetFromForm = () => {
    const freshLatex = resumeToLatexFromMetadata(draft.content || ({} as any), draft.metadata);
    setLatexSource(freshLatex);
    lastSelfCompiledContentJsonRef.current = JSON.stringify(draft.content || {});
    setIsCustomEdited(false);
    toast.info('LaTeX code reset to current form data.');
  };

  // AI-powered LaTeX Adapter: parses complex or non-standard LaTeX into visual Content Editor sections
  const handleAiAdaptLatex = async () => {
    if (!latexSource.trim()) {
      toast.info('LaTeX editor is empty. Nothing to adapt.');
      return;
    }
    setAiEnhancing(true);
    try {
      toast.loading('AI is analyzing and adapting LaTeX into form sections...', { id: 'ai-adapt' });
      const res = await aiParseLatex(latexSource);
      if (res?.content) {
        lastSelfCompiledContentJsonRef.current = JSON.stringify(res.content);
        if (updateDraft) updateDraft({ content: res.content });
        const cleanLatex = resumeToLatexFromMetadata(res.content, draft.metadata);
        setLatexSource(cleanLatex);
        setIsCustomEdited(false);
        const timestamp = new Date().toLocaleTimeString();
        setLastCompiledAt(timestamp);
        setCompileLogs([
          `[${timestamp}] AI Auto-Adaptation completed using ${res.provider} (${res.model}).`,
          `[${timestamp}] All visual Content Editor sections and Live Preview adapted to match LaTeX source.`,
          `[${timestamp}] LaTeX source normalized to standard ATS-compatible syntax.`,
        ]);
        toast.success('LaTeX adapted with AI! Form and live preview synchronized.', { id: 'ai-adapt' });
      }
    } catch {
      toast.error('AI adaptation failed. Using AST compiler fallback.', { id: 'ai-adapt' });
      handleSyncToForm();
    } finally {
      setAiEnhancing(false);
    }
  };

  // AI-powered LaTeX Assistant: formats, cleans, and optimizes the current LaTeX code
  const handleAiEnhanceLatex = async () => {
    setAiEnhancing(true);
    try {
      const compiled = compileLatexDocument(latexSource);
      toast.loading('AI is formatting & enhancing LaTeX resume...', { id: 'ai-latex' });

      const enhanced = await aiEnhanceResume(
        compiled.content,
        'Format, polish, and optimize all resume sections for high-impact ATS readability, professional phrasing, and perfect LaTeX formatting.'
      );

      if (enhanced?.content) {
        lastSelfCompiledContentJsonRef.current = JSON.stringify(enhanced.content);
        if (updateDraft) updateDraft({ content: enhanced.content });
        const newLatex = resumeToLatexFromMetadata(enhanced.content, draft.metadata);
        setLatexSource(newLatex);
        setIsCustomEdited(false);
        toast.success('LaTeX resume enhanced by AI and synchronized!', { id: 'ai-latex' });
      }
    } catch {
      toast.error('AI enhancement failed. Please check connection or API key.', { id: 'ai-latex' });
    } finally {
      setAiEnhancing(false);
    }
  };

  const handleCompile = async () => {
    setCompiling(true);
    const startTime = performance.now();
    try {
      // 1. If empty or whitespace, instantly clear draft, preview, and form
      if (!latexSource.trim()) {
        const empty = createEmptyContent();
        lastSelfCompiledContentJsonRef.current = JSON.stringify(empty);
        if (updateDraft) {
          updateDraft({
            content: empty,
          });
        }
        setDiagnostics([]);
        const timestamp = new Date().toLocaleTimeString();
        setLastCompiledAt(timestamp);
        setCompileLogs([
          `[${timestamp}] LaTeX source cleared.`,
          `[${timestamp}] Document cleared: 0 sections, 0 lines.`,
          `[${timestamp}] Live preview and Content Editor sections are now completely empty.`,
        ]);
        toast.success('Resume cleared. Live preview is now empty.');
        return;
      }

      // 2. Compile LaTeX into draft model and sync live preview immediately
      const result = compileLatexDocument(latexSource);
      lastSelfCompiledContentJsonRef.current = JSON.stringify(result.content);

      if (updateDraft) {
        updateDraft({
          content: result.content,
          metadata: {
            ...draft.metadata,
            ...(result.metadata?.pageSize ? { pageSize: result.metadata.pageSize } : {}),
            ...(result.metadata?.pageMargin ? { pageMargin: result.metadata.pageMargin } : {}),
            ...(result.metadata?.theme ? { theme: { ...draft.metadata?.theme, ...result.metadata.theme } } : {}),
          },
        });
      }
      setDiagnostics(result.diagnostics);

      const res = await fetch(`${API_URL}/api/v1/export/latex/compile`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          tex: latexSource,
          content: result.content,
          metadata: draft.metadata,
        }),
      });

      const elapsed = Math.round(performance.now() - startTime);

      if (!res.ok) {
        throw new Error(`Compilation failed with status ${res.status}`);
      }

      const blob = await res.blob();
      setCompiledBlob(blob);
      if (pdfBlobUrl) URL.revokeObjectURL(pdfBlobUrl);
      const url = URL.createObjectURL(blob);
      setPdfBlobUrl(url);

      const timestamp = new Date().toLocaleTimeString();
      setLastCompiledAt(timestamp);
      setCompileLogs([
        `[${timestamp}] Starting LaTeX compilation...`,
        `[${timestamp}] Parsing geometry: ${draft.metadata?.pageSize || 'letter'}, margin ${draft.metadata?.pageMargin || 0.6}in`,
        `[${timestamp}] Compiling ${latexSource.split('\n').length} lines of TeX source...`,
        `[${timestamp}] Processing glyph tables & ATS-compliant vector PDF stream...`,
        `[${timestamp}] Compilation successful in ${elapsed}ms. 0 errors, 0 warnings.`,
        `[${timestamp}] Output generated: ${blob.size} bytes. Live preview and content updated.`,
      ]);

      toast.success(`LaTeX compiled in ${elapsed}ms! Click "Save PDF" to download.`);
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Compilation failed';
      setCompileLogs((prev) => [
        ...prev,
        `[${new Date().toLocaleTimeString()}] Error: ${msg}`,
      ]);
      toast.error('Failed to compile LaTeX document.');
    } finally {
      setCompiling(false);
    }
  };



  const handleDownloadCompiledPdf = async () => {
    const filename = buildExportFilename(draft.content, draft.title, 'pdf');
    if (compiledBlob) {
      const saved = await triggerFileSave(compiledBlob, filename);
      if (saved) toast.success(`Saved ${filename}!`);
      return;
    }

    if (pdfBlobUrl) {
      try {
        const res = await fetch(pdfBlobUrl);
        const blob = await res.blob();
        const saved = await triggerFileSave(blob, filename);
        if (saved) toast.success(`Saved ${filename}!`);
        return;
      } catch {
        // Fall through
      }
    }

    await handleCompile();
  };

  return (
    <div className="space-y-5">
      {/* Compiler Action Bar */}
      <Card className="rounded-2xl border-border bg-card shadow-sm">
        <CardHeader className="pb-3">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
            <div className="flex items-center gap-2">
              <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-orange-500 text-white font-bold">
                <Code2 className="h-4 w-4" />
              </div>
              <div>
                <CardTitle className="text-base font-bold">Real-Time LaTeX Compiler Engine</CardTitle>
                <CardDescription className="text-xs">
                  Compile your resume directly with real-time pdfTeX syntax generation.
                </CardDescription>
              </div>
            </div>

            <div className="flex flex-wrap items-center gap-2">
              <Button
                size="sm"
                variant="outline"
                onClick={handleCopy}
                className="h-8 text-xs"
              >
                {copied ? <Check className="h-3.5 w-3.5 mr-1 text-emerald-500" /> : <Copy className="h-3.5 w-3.5 mr-1" />}
                {copied ? 'Copied' : 'Copy .tex'}
              </Button>
              <Button
                size="sm"
                variant="outline"
                onClick={handleDownloadTex}
                className="h-8 text-xs"
              >
                <FileCode className="h-3.5 w-3.5 mr-1" />
                Download .tex
              </Button>
              {isCustomEdited && (
                <>
                  <Button
                    size="sm"
                    variant="outline"
                    onClick={handleSyncToForm}
                    className="h-8 text-xs text-orange-600 border-orange-200 hover:bg-orange-50 dark:hover:bg-orange-950/20"
                    title="Parse LaTeX edits back into the visual Content Editor"
                  >
                    Sync to Form
                  </Button>
                  <Button
                    size="sm"
                    variant="ghost"
                    onClick={handleResetFromForm}
                    className="h-8 text-xs text-muted-foreground hover:text-foreground"
                    title="Reset to match the visual form data"
                  >
                    Reset
                  </Button>
                </>
              )}
              <Button
                size="sm"
                variant="outline"
                onClick={handleAiAdaptLatex}
                disabled={aiEnhancing}
                className="h-8 text-xs text-orange-600 dark:text-orange-400 border-orange-300 dark:border-orange-800 hover:bg-orange-50 dark:hover:bg-orange-950/20 font-semibold"
                title="Use AI to automatically adapt arbitrary LaTeX into the visual Content Editor sections and live preview"
              >
                <Sparkles className={`h-3.5 w-3.5 mr-1 ${aiEnhancing ? 'animate-spin text-orange-500' : 'text-orange-500'}`} />
                {aiEnhancing ? 'Adapting...' : 'AI Adapt LaTeX'}
              </Button>
              <Button
                size="sm"
                variant="outline"
                onClick={handleAiEnhanceLatex}
                disabled={aiEnhancing}
                className="h-8 text-xs text-orange-600 dark:text-orange-400 border-orange-300 dark:border-orange-800 hover:bg-orange-50 dark:hover:bg-orange-950/20 font-semibold"
                title="Use AI to automatically polish, adapt, and format your LaTeX resume"
              >
                <Sparkles className={`h-3.5 w-3.5 mr-1 ${aiEnhancing ? 'animate-spin text-orange-500' : 'text-orange-500'}`} />
                {aiEnhancing ? 'Enhancing...' : 'AI Enhance'}
              </Button>
              <Button
                size="sm"
                variant={realtimeSync ? 'default' : 'outline'}
                onClick={() => {
                  const next = !realtimeSync;
                  setRealtimeSync(next);
                  toast.info(next ? 'Real-time compilation active — preview updates as you type.' : 'Real-time compilation paused.');
                }}
                className={`h-8 text-xs font-semibold ${realtimeSync ? 'bg-emerald-600 hover:bg-emerald-700 text-white' : 'text-muted-foreground'}`}
                title="Automatically compile and update the live preview as you type"
              >
                <Zap className="h-3.5 w-3.5 mr-1" />
                {realtimeSync ? 'Live Sync: ON' : 'Live Sync: OFF'}
              </Button>
              <Button
                size="sm"
                onClick={handleCompile}
                disabled={compiling}
                className="h-8 text-xs bg-orange-500 text-white hover:bg-orange-600 font-semibold shadow-sm"
              >
                <Play className={`h-3.5 w-3.5 mr-1.5 ${compiling ? 'animate-spin' : 'fill-current'}`} />
                {compiling ? 'Compiling...' : 'Compile LaTeX'}
              </Button>
            </div>
          </div>
        </CardHeader>


        <CardContent className="space-y-4">
          {/* Compilation Status Strip */}
          <div className="flex items-center justify-between rounded-xl border border-border bg-muted/40 px-3 py-2 text-xs">
            <div className="flex items-center gap-2">
              <span className={`h-2 w-2 rounded-full ${lastCompiledAt ? 'bg-emerald-500 animate-pulse' : 'bg-orange-400'}`} />
              <span className="font-mono text-muted-foreground">
                Status: {lastCompiledAt ? `Real-Time Compiled at ${lastCompiledAt}` : 'Real-time Live Sync Active'}
                {diagnostics.some((d) => d.type === 'error') ? ' (Errors detected)' : ' (0 Errors)'}
              </span>
            </div>
            {pdfBlobUrl && (
              <Button
                size="sm"
                variant="outline"
                onClick={handleDownloadCompiledPdf}
                className="h-7 text-xs text-orange-600 dark:text-orange-400 border-orange-300 dark:border-orange-800 hover:bg-orange-50 dark:hover:bg-orange-950/20 font-semibold shadow-xs"
              >
                <FileDown className="h-3.5 w-3.5 mr-1" />
                Save PDF ({buildExportFilename(draft.content, draft.title, 'pdf')})
              </Button>
            )}
          </div>


          {/* LaTeX Code Editor / Viewer */}
          <div className="relative rounded-xl border border-border bg-slate-950 text-slate-100 font-mono text-xs overflow-hidden shadow-inner">
            <div className="flex items-center justify-between border-b border-slate-800 bg-slate-900 px-3 py-1.5 text-[11px] text-slate-400">
              <span className="flex items-center gap-1.5">
                <FileCode className="h-3.5 w-3.5 text-orange-400" />
                resume.tex (pdflatex / ATS-optimized)
                {isCustomEdited && (
                  <span className="ml-2 rounded bg-orange-500/20 px-1.5 py-0.5 text-[10px] text-orange-300">
                    Modified
                  </span>
                )}
              </span>
              <span>{latexSource.split('\n').length} lines</span>
            </div>
            <textarea
              value={latexSource}
              onChange={(e) => {
                setLatexSource(e.target.value);
                setIsCustomEdited(true);
              }}
              className="w-full h-80 bg-transparent p-3 text-xs font-mono resize-y focus:outline-none focus:ring-0 leading-relaxed text-slate-200 selection:bg-orange-500/30"
              spellCheck={false}
            />
          </div>

          {/* Terminal / Compiler Logs */}
          <div className="rounded-xl border border-border bg-slate-900 p-3 text-slate-300 font-mono text-[11px] space-y-1">
            <div className="flex items-center gap-1.5 text-slate-400 border-b border-slate-800 pb-1.5 mb-1.5">
              <Terminal className="h-3.5 w-3.5 text-orange-400" />
              <span>Compiler Console Log</span>
            </div>
            {compileLogs.map((log, idx) => (
              <div key={idx} className="leading-tight text-slate-400">
                {log}
              </div>
            ))}
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
